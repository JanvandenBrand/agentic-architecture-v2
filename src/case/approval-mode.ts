import type { ValidationError } from "../types.js";
import { isRecord } from "../common/json.js";
import { readSignature, verifyKeyTransition } from "../identity/signature.js";
import type { LoadedRecord } from "./records.js";
import { asApproval, type Approval } from "./review-records.js";

const invariant = "approval-mode";

export type ApprovalMode = "synthetic" | "self-asserted" | "human-verified";

const approvalModes = new Set<string>([
  "synthetic",
  "self-asserted",
  "human-verified",
]);

export function isApprovalMode(value: string): value is ApprovalMode {
  return approvalModes.has(value);
}

/**
 * Resolves the assurance an approval actually carries from its recorded
 * evidence. It never reads the declared mode: a claim is the thing being
 * checked, not the check.
 */
export function resolveApprovalMode(approval: Approval): ApprovalMode {
  if (approval.signatureVerified) {
    return "human-verified";
  }
  return approval.syntheticTestEvidence ? "synthetic" : "self-asserted";
}

export function approvalModeLabel(mode: ApprovalMode): string {
  switch (mode) {
    case "synthetic":
      return "Synthetic test evidence. Generated by the offline harness; no human decision was made.";
    case "human-verified":
      return "Human-verified. The approver signature verifies against the case approval key.";
    default:
      return "Self-asserted. Recorded without verification of the approver's identity.";
  }
}

export interface ApprovalModeOptions {
  /**
   * True when this machine holds an architect approval key. Holding a key means
   * a real decision is expected to carry it, so an unsigned approval stops being
   * a quiet fallback and becomes a failure. Synthetic harness evidence is exempt:
   * it never claims to be a human decision.
   */
  requireSignedApprovals?: boolean;
}

export function validateApprovalModes(
  records: LoadedRecord[],
  options: ApprovalModeOptions = {},
): ValidationError[] {
  const errors: ValidationError[] = [];

  for (const record of records) {
    const approval = asApproval(record);
    if (!approval || !isRecord(record.value.extensions)) continue;
    const extensions = record.value.extensions;
    if ("signature" in extensions && !approval.signatureVerified &&
        approval.claimedMode !== "human-verified") {
      errors.push({
        file: record.file, invariant,
        message: "The recorded approval signature is malformed or does not verify.",
        remediation: "Preserve historical evidence and investigate the failed signature; do not downgrade its assurance claim.",
      });
    }
    if (approval.signatureVerified && "keyFingerprint" in extensions &&
        extensions.keyFingerprint !== approval.keyFingerprint) {
      errors.push({
        file: record.file, invariant,
        message: "The redundant key fingerprint does not match the verified signature identity.",
        remediation: "Use the signature-derived identity; do not rewrite signed historical metadata.",
      });
    }
    if (!approval.signatureVerified && "keyRotation" in extensions) {
      errors.push({
        file: record.file, invariant,
        message: "A key rotation requires a verified new-key decision and predecessor countersignature.",
        remediation: "Do not treat rotation metadata or lost-key recovery claims as authority.",
      });
    }
  }

  for (const approval of records
    .map(asApproval)
    .filter((value): value is Approval => value !== undefined)) {
    const resolved = resolveApprovalMode(approval);
    if (options.requireSignedApprovals && resolved === "self-asserted") {
      errors.push({
        file: approval.file,
        invariant,
        message:
          "This machine holds an architect approval key, so a human decision must be signed. This decision is not.",
        remediation:
          "Record the decision yourself with the approval command, in your own terminal, outside any agent session.",
      });
    }

    const claimed = approval.claimedMode;
    if (claimed === undefined) {
      continue;
    }
    if (!isApprovalMode(claimed)) {
      errors.push({
        file: approval.file,
        invariant,
        message: `Approval declares unknown assurance mode "${claimed}".`,
        remediation: `Set extensions.approvalMode to one of ${[...approvalModes].sort().join(", ")}.`,
      });
      continue;
    }

    if (claimed !== resolved) {
      errors.push({
        file: approval.file,
        invariant,
        message: `Approval declares assurance mode "${claimed}" but its recorded evidence supports only "${resolved}".`,
        remediation:
          "Declare the mode the evidence supports. A stronger claim is never accepted on the strength of the claim itself.",
      });
    }
  }

  return [...errors, ...validateSignatureContinuity(records)];
}

/**
 * Once any approval in a case is signed, every later approval must be signed by
 * the same key. Without this an agent could simply omit the signature and fall
 * back to the weaker self-asserted mode, which would defeat the whole control.
 */
function validateSignatureContinuity(
  records: LoadedRecord[],
): ValidationError[] {
  const approvals = records
    .map(asApproval)
    .filter((value): value is Approval => value !== undefined)
    .sort(
      (left, right) =>
        Date.parse(left.decidedAt) - Date.parse(right.decidedAt) ||
        (left.file < right.file ? -1 : left.file > right.file ? 1 : 0),
    );
  const signed = approvals.filter(({ signatureVerified }) => signatureVerified);
  if (signed.length === 0) {
    return [];
  }

  const errors: ValidationError[] = [];
  const anchor = signed[0];
  const firstSignedAt = anchor ? Date.parse(anchor.decidedAt) : 0;
  let currentPublicKey: string | undefined;
  let currentFingerprint: string | undefined;
  const values = new Map(records.map(({ file, value }) => [file, value]));

  for (const approval of approvals) {
    if (!approval.signatureVerified) {
      if (Date.parse(approval.decidedAt) >= firstSignedAt) {
        errors.push({
          file: approval.file,
          invariant,
          message:
            "This case records verified approvals, but this decision carries no verified signature.",
          remediation:
            "Sign every decision once a case has one signed decision. Assurance is never allowed to weaken over the life of a case.",
        });
      }
      continue;
    }
    const value = values.get(approval.file)!;
    const signature = readSignature(value)!;
    if (isRecord(value.extensions) && "keyFingerprint" in value.extensions &&
        value.extensions.keyFingerprint !== signature.keyFingerprint) continue;
    const transition = verifyKeyTransition(value, signature.publicKeyPem, currentPublicKey);
    if (!transition.verified) {
      errors.push({
        file: approval.file,
        invariant,
        message: `This decision is signed by key ${signature.keyFingerprint}, but the case is anchored to ${currentFingerprint ?? "its original verified key"}: ${transition.reason}.`,
        remediation:
          "Use the established key or its countersignature over this exact case decision and old/new keys. Lost-key recovery is not supported.",
      });
      continue;
    }
    currentPublicKey = signature.publicKeyPem;
    currentFingerprint = signature.keyFingerprint;
  }

  return errors;
}
